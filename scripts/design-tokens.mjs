import { readFile, writeFile } from "node:fs/promises";
const t = JSON.parse(
  await readFile("src/renderer/design-system/tokens.json", "utf8"),
);
const vars = (o) =>
  Object.entries(o)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");
await writeFile(
  "src/renderer/design-system/tokens.css",
  `/* Generated by scripts/design-tokens.mjs from tokens.json. */\n:root {\n${vars(t.dimensions)}\n${vars(Object.fromEntries(Object.entries(t.primitives).map(([k, v]) => ["brand-" + k, v])))}\n  --font-heading: Sora, Inter, sans-serif;\n  --font-ui: Inter, -apple-system, BlinkMacSystemFont, sans-serif;\n  --mono: 'JetBrains Mono', ui-monospace, SFMono-Regular, Menlo, monospace;\n  --shadow: 0 8px 24px #00000018;\n  --overlay: #05091ccc;\n  --video-bg: #060a1a;\n  --video-text: #ffffff;\n  --video-error: #ffb4bd;\n  color-scheme: dark;\n${vars(t.dark)}\n}\n:root[data-theme="light"] {\n  color-scheme: light;\n${vars(t.light)}\n}\n`,
);
